-- ══════════════════════════════════════════════════════════════════════════
-- 자리후(seat) — memo 컬럼 추가 : 표 오른쪽 '비고'(자유 메모판)
-- ══════════════════════════════════════════════════════════════════════════
-- 목적: 자리안내·주문서관리 표 오른쪽 끝에 행 단위 자유 메모 칸을 둔다.
--       두 역할 모두 읽고 수정할 수 있는 공용 메모판(유저 지시 2026-08-02).
--
-- 기존 notes 와의 구분:
--   notes — '특이사항'. 스테이션(카이막/커피) 카드에도 그대로 표시되는 제조 지시성 메모.
--   memo  — '비고'. 표에서만 보이는 자유 메모(스테이션 카드에 노출하지 않음).
--
-- ★안전성:
--   - 엄격히 additive: 신규 text, nullable, DEFAULT 없음(=NULL). 기존 컬럼/CHECK/트리거/
--     인덱스/시퀀스 무변경 → 기존 앱 로직·쿼리 회귀 0.
--   - RLS 무변경: seat_orders_rw 는 행 단위(can_in_workspace(workspace_id,'editor')) →
--     컬럼 추가에 정책 수정 불필요(컬럼 단위 GRANT 없음). 두 역할 모두 editor 권한으로 진입하므로
--     '둘 다 읽기·수정 가능' 요구는 기존 정책으로 이미 충족.
--   - Realtime 무변경: REPLICA IDENTITY FULL + publication 등록 → 새 컬럼 payload 자동 포함
--     (한쪽에서 적은 비고가 다른 역할 화면에 1~2초 내 반영, R7).
--   - updated_at 트리거 무변경.
--   - 재실행 안전: ADD COLUMN IF NOT EXISTS.
--   - 백필 불필요(NULL = 빈 메모, 앱은 '' 로 표시).
--
-- 적용: supabase-guardian 검수 → 유저 승인 후 → thinkmap 통합세션이 적용(tmseat 직접적용 금지).
--       ★앱 배포는 이 마이그 적용 이후여야 함(컬럼 부재 시 { memo: ... } UPDATE 가
--        PGRST 컬럼오류 → 저장실패 토스트). 마이그 먼저, 그 다음 seat 위성 재배포.
-- ══════════════════════════════════════════════════════════════════════════

ALTER TABLE seat_orders
  ADD COLUMN IF NOT EXISTS memo text;

COMMENT ON COLUMN seat_orders.memo IS
  '비고 — 표 오른쪽 자유 메모판(행 단위). 자리안내·주문서관리 공용. 스테이션 카드에는 노출하지 않는다(그건 notes).';
